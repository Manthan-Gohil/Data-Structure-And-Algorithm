// polymorphism -> Polymorphism means "one name, many forms." In C++, it allows the same function name, operator, or interface to behave differently depending on the arguments or the object involved.
// For example, the same function draw() could draw a circle, rectangle, or triangle depending on which object calls it.

// Types of polymorphism
// 1. Compile-time polymorphism
// The compiler determines which function to call during compilation.
// - Function overloading
// - Operator overloading

// 2. Runtime polymorphism
// The function implementation is selected at runtime, typically through virtual functions.
// - Function overriding with virtual functions
