// difference between constructor and destructor

// constructor ->
// 1. it allocates memory to an object
// 2. the name of the constructor is the same name as class name
// 3. it is being automatically called at the time of object creation
// 4. we can pass arguments through constructor
// 5. we can declare multiple constructor in a class
// 6. constructor can be overloaded
// 7. constructor has various types -> default, parametrized and copy

// destructor -> destructor is a special member function that is executed automatically when an object is destroyed that has been created by constructor.
// 1. it de-allocates memory to an object
// 2. the name of the destructor is the same name as class name but preceding tilde(~) sign
// 3. it is automatically called at the time of object termination
// 4. we can not pass arguments through destructor
// 5. we can declare only one destructor in a classoverloading is not possible
// 6. no any types of destrcutor
